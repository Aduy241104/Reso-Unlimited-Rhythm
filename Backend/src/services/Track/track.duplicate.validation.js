import { StatusCodes } from "http-status-codes";
import AudioFingerprint from "../../models/AudioFingerprint.js";
import Track from "../../models/Track.js";
import { AppError } from "../../utils/AppError.js";

export const TRACK_TITLE_VERSION_EXISTS_CODE = "TRACK_TITLE_VERSION_EXISTS";
export const TRACK_AUDIO_FINGERPRINT_EXISTS_CODE = "TRACK_AUDIO_FINGERPRINT_EXISTS";

export const normalizeTrackVersionTitle = (versionTitle) =>
    typeof versionTitle === "string" ? versionTitle.trim() : "";

export const buildTrackTitleVersionExistsError = () =>
    new AppError(
        "Bạn đã có một bài hát cùng tên và cùng phiên bản. Vui lòng đổi tên bài hát hoặc tên phiên bản.",
        StatusCodes.CONFLICT,
        {
            code: TRACK_TITLE_VERSION_EXISTS_CODE,
            field: "title",
            fields: ["artist_artistId", "title", "versionTitle"],
            message: "Bài hát cùng tên và cùng phiên bản đã tồn tại.",
        }
    );

export const assertTrackTitleVersionAvailable = async ({
    artistId,
    title,
    versionTitle = "",
    excludeTrackId = null,
} = {}) => {
    if (!artistId || !title) {
        return;
    }

    const filter = {
        artist_artistId: artistId,
        title,
        versionTitle: normalizeTrackVersionTitle(versionTitle),
        isDeleted: { $ne: true },
    };

    if (excludeTrackId) {
        filter._id = { $ne: excludeTrackId };
    }

    const existingTrack = await Track.findOne(filter)
        .select("_id title versionTitle")
        .lean();

    if (existingTrack) {
        throw buildTrackTitleVersionExistsError();
    }
};

export const normalizeTrackSourceAudioHash = (sourceAudioHash) => {
    const normalizedHash = typeof sourceAudioHash === "string"
        ? sourceAudioHash.trim().toLowerCase()
        : "";

    // sourceAudioHash is generated by the upload endpoint as a SHA-256 hash.
    // Ignore malformed client-provided values instead of treating them as a
    // valid fingerprint reservation.
    return /^[a-f0-9]{64}$/.test(normalizedHash) ? normalizedHash : "";
};

export const buildTrackAudioFingerprintExistsError = () =>
    new AppError(
        "Bài hát này đã tồn tại với cùng fingerprint trong các bài hát của nghệ sĩ.",
        StatusCodes.CONFLICT,
        {
            code: TRACK_AUDIO_FINGERPRINT_EXISTS_CODE,
            field: "audioAnalysis.sourceAudioHash",
            fields: ["artist_artistId", "audioAnalysis.sourceAudioHash"],
            message: "Không thể tạo bài hát vì audio fingerprint đã tồn tại trong cùng nghệ sĩ.",
        }
    );

export const assertTrackAudioFingerprintAvailable = async ({
    artistId,
    sourceAudioHash,
    excludeTrackId = null,
} = {}) => {
    const normalizedHash = normalizeTrackSourceAudioHash(sourceAudioHash);

    if (!artistId || !normalizedHash) {
        return;
    }

    const trackFilter = {
        artist_artistId: artistId,
        isDeleted: { $ne: true },
        "fingerprintScreening.audioHash": normalizedHash,
    };

    if (excludeTrackId) {
        trackFilter._id = { $ne: excludeTrackId };
    }

    // The hash is copied to Track before the asynchronous fingerprint job is
    // scheduled, so later create requests can detect a duplicate while the
    // first fingerprint record is still pending.
    const existingTrack = await Track.findOne(trackFilter)
        .select("_id title")
        .lean();

    if (existingTrack) {
        throw buildTrackAudioFingerprintExistsError();
    }

    // Older tracks may not have copied the hash into Track yet. Fall back to
    // the fingerprint catalog and verify ownership against the current Track.
    const fingerprintRecords = await AudioFingerprint.find({
        algorithm: "chromaprint",
        algorithmVersion: "chromaprint-v1",
        sourceAudioHash: normalizedHash,
    })
        .select("trackId audioVersion")
        .lean();

    for (const fingerprintRecord of fingerprintRecords) {
        if (!fingerprintRecord?.trackId) continue;

        const candidateFilter = {
            _id: fingerprintRecord.trackId,
            artist_artistId: artistId,
            isDeleted: { $ne: true },
        };

        if (excludeTrackId) {
            candidateFilter._id = {
                $in: [fingerprintRecord.trackId],
                $ne: excludeTrackId,
            };
        }

        const candidateTrack = await Track.findOne(candidateFilter)
            .select("_id title audioVersion")
            .lean();

        // Do not use a stale fingerprint from an older audio version after an
        // artist has replaced the track audio.
        if (
            candidateTrack &&
            Number(fingerprintRecord.audioVersion || 1) === Number(candidateTrack.audioVersion || 1)
        ) {
            throw buildTrackAudioFingerprintExistsError();
        }
    }
};
